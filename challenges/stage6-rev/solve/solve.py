#!/usr/bin/env python3
# Extracted bytes from DAT_00102020
ghidra_bytes = [
    0x1F, 0x22, 0x24, 0x42, 0x25, 0x38, 0xCA, 0xDF,
    0xDB, 0xD7, 0xE5, 0xEB, 0x83, 0x8C, 0x85, 0xF7,
    0xF8, 0xFC, 0x99, 0x9D, 0xA9, 0xBF, 0xA0
]

passkey = ""
for i, b in enumerate(ghidra_bytes):
    key = (0x5A + (i * 7)) & 0xFF
    passkey += chr(b ^ key)

print(f"Decoded Passkey: {passkey}")